// Builds places.js (every neighborhood and city the app knows) from the raw boundary files in data/raw.
//   node scripts/build-places.mjs
// Sources:
//   data/raw/la-times-neighborhoods.geojson  LA Times "Mapping L.A." — the 114 City of LA neighborhoods (geohub.lacity.org)
//   data/raw/la-county-cities.geojson        LA County DPW city boundaries — the 88 cities (land, piers, breakwaters only)
// The City of LA itself is left out: its neighborhoods cover it. Unincorporated county land has no names in the
// county file, so it isn't a place yet; events there fall back to the nearest place.
import { readFileSync, writeFileSync } from 'node:fs';

const TOL = 0.00025;   // simplify to ~25 m: plenty for "which neighborhood is this in", and keeps the file small
const DP = 4;          // ~11 m coordinate precision

// the county file drops the tilde
const RENAME = { 'La Canada Flintridge':'La Cañada Flintridge' };

const read = f => JSON.parse(readFileSync(new URL('../data/raw/'+f, import.meta.url)));
const polys = g => g.type==='Polygon' ? [g.coordinates] : g.coordinates;

// Douglas-Peucker on one ring
function simplify(pts){
  if(pts.length<=4) return pts;
  const keep=new Uint8Array(pts.length); keep[0]=keep[pts.length-1]=1;
  const stack=[[0,pts.length-1]];
  while(stack.length){
    const [a,b]=stack.pop(); let idx=-1, max=TOL;
    const [x1,y1]=pts[a], [x2,y2]=pts[b], dx=x2-x1, dy=y2-y1, L=dx*dx+dy*dy;
    for(let i=a+1;i<b;i++){
      const [x,y]=pts[i]; let t=L? ((x-x1)*dx+(y-y1)*dy)/L : 0; t=Math.max(0,Math.min(1,t));
      const d=Math.hypot(x-(x1+t*dx), y-(y1+t*dy)); if(d>max){ max=d; idx=i; }
    }
    if(idx>0){ keep[idx]=1; stack.push([a,idx],[idx,b]); }
  }
  return pts.filter((_,i)=>keep[i]);
}
const area = r => { let s=0; for(let i=0,j=r.length-1;i<r.length;j=i++) s+=(r[j][0]-r[i][0])*(r[j][1]+r[i][1]); return Math.abs(s/2); };
function inside(x,y,rings){ let c=false; for(const r of rings) for(let i=0,j=r.length-1;i<r.length;j=i++){ const [xi,yi]=r[i],[xj,yj]=r[j]; if((yi>y)!==(yj>y) && x<(xj-xi)*(y-yi)/(yj-yi)+xi) c=!c; } return c; }
function edgeDist(x,y,rings){ let m=Infinity; for(const r of rings) for(let i=0,j=r.length-1;i<r.length;j=i++){ const [x1,y1]=r[j],[x2,y2]=r[i], dx=x2-x1, dy=y2-y1, L=dx*dx+dy*dy; let t=L?((x-x1)*dx+(y-y1)*dy)/L:0; t=Math.max(0,Math.min(1,t)); m=Math.min(m,Math.hypot(x-(x1+t*dx),y-(y1+t*dy))); } return m; }
// label point: the spot in the biggest piece farthest from its edges (a coarse grid search, then a finer one around the best)
function center(ps){
  const rings=ps.reduce((a,b)=>area(b[0])>area(a[0])?b:a);
  let xs=rings[0].map(p=>p[0]), ys=rings[0].map(p=>p[1]);
  let x0=Math.min(...xs), x1=Math.max(...xs), y0=Math.min(...ys), y1=Math.max(...ys), best=null, bd=-1;
  for(let pass=0;pass<3;pass++){
    const sx=(x1-x0)/24, sy=(y1-y0)/24;
    for(let x=x0;x<=x1;x+=sx) for(let y=y0;y<=y1;y+=sy) if(inside(x,y,rings)){ const d=edgeDist(x,y,rings); if(d>bd){ bd=d; best=[x,y]; } }
    if(!best) break;
    x0=best[0]-sx*2; x1=best[0]+sx*2; y0=best[1]-sy*2; y1=best[1]+sy*2;
  }
  return best || rings[0][0];
}

const groups = new Map();   // name -> { type, polygons }
const add = (name,type,g) => { name=RENAME[name]||name; if(!groups.has(name)) groups.set(name,{type,ps:[]}); groups.get(name).ps.push(...polys(g)); };
for(const f of read('la-times-neighborhoods.geojson').features) add(f.properties.name,'hood',f.geometry);
for(const f of read('la-county-cities.geojson').features) if(f.properties.CITY_NAME!=='Los Angeles') add(f.properties.CITY_NAME,'city',f.geometry);

const round = v => +v.toFixed(DP);
const out = [...groups].sort((a,b)=>a[0].localeCompare(b[0])).map(([name,{type,ps}])=>{
  const c = center(ps);
  // drop slivers that vanish at this tolerance; flat rings [x,y,x,y,...] keep the file small
  const shapes = ps.map(p=>p.map(r=>simplify(r)).filter(r=>r.length>=4)).filter(p=>p.length)
    .map(p=>p.map(r=>r.flatMap(([x,y])=>[round(x),round(y)])));
  const all = shapes.flat(2), xs=all.filter((_,i)=>i%2===0), ys=all.filter((_,i)=>i%2===1);
  return { name, type, lat:round(c[1]), lng:round(c[0]), bbox:[Math.min(...xs),Math.min(...ys),Math.max(...xs),Math.max(...ys)], shapes };
});

const hoods = out.filter(p=>p.type==='hood').length, cities = out.length-hoods;
writeFileSync(new URL('../places.js', import.meta.url),
  `// Generated by scripts/build-places.mjs from data/raw. Don't edit by hand: change the script or the source files and rerun it.\n`+
  `// ${hoods} City of LA neighborhoods (LA Times Mapping L.A.) + ${cities} LA County cities (LA County DPW).\n`+
  `// shapes: one entry per piece, each a list of rings [lng,lat,lng,lat,...]; the first ring is the outline, the rest are holes.\n`+
  `const PLACE_DATA = [\n${out.map(p=>JSON.stringify(p)).join(',\n')}\n];\n`);
console.log(`${out.length} places (${hoods} neighborhoods, ${cities} cities)`);
